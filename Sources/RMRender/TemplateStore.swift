import Foundation
import RMMarks
import Synchronization

/// Where page templates come from.
///
/// A page names its template (`"P Lines medium"`), and a source decides what,
/// if anything, that name resolves to: the set bundled with this package
/// (`BundledTemplates`), a directory of `.template` files the host carries,
/// files it fetched, or templates it builds in memory. A name the source does
/// not know leaves the page without a background.
public protocol TemplateSource: Sendable {
    /// Every name this source can supply. It lists the templates a hand
    /// can be written along (`TemplateStore.ruledTemplates(pageSize:)`); a
    /// source that cannot enumerate may return an empty array and still
    /// answer `templateData(named:)`.
    func templateNames() -> [String]

    /// The JSON of the template with this name, or `nil` if there is none.
    func templateData(named name: String) -> Data?
}

/// Templates read from a directory: `<name>.template` files, one per
/// template, named as pages refer to them.
public struct TemplateDirectory: TemplateSource {
    public let url: URL

    public init(url: URL) {
        self.url = url
    }

    public func templateNames() -> [String] {
        let files = (try? FileManager.default.contentsOfDirectory(
            at: url,
            includingPropertiesForKeys: nil,
            options: [.skipsHiddenFiles]
        )) ?? []
        return files
            .filter { $0.pathExtension == "template" }
            .map { $0.deletingPathExtension().lastPathComponent }
            .sorted()
    }

    public func templateData(named name: String) -> Data? {
        // A name is a file name and nothing more: one that would step out of
        // the directory is not a template this source holds.
        guard !name.isEmpty, !name.contains("/"), !name.hasPrefix(".") else { return nil }
        return try? Data(contentsOf: url.appendingPathComponent(name).appendingPathExtension("template"))
    }
}

/// The templates bundled with this package: line, grid and dot paper,
/// planners, storyboards, music and drawing guides, filed under the names the
/// tablet gives its own templates so that a page naming one of them is drawn
/// with a background. The drawings are this package's own; the spacings and
/// insets are the ones handwriting on such a page was laid along.
///
/// `TemplateStore.shared` draws from this until the host installs another
/// source. They are generated by `Scripts/generate-templates.py`.
public struct BundledTemplates: TemplateSource {
    /// The folder the package carries them in, where it could be found.
    private static let directory: TemplateDirectory? = Bundle.module
        .url(forResource: "Templates", withExtension: nil)
        .map { TemplateDirectory(url: $0) }

    public init() {}

    public func templateNames() -> [String] {
        Self.directory?.templateNames() ?? []
    }

    public func templateData(named name: String) -> Data? {
        Self.directory?.templateData(named: name)
    }
}

/// Several sources asked in order: a name is answered by the first source
/// that has it.
///
/// What lets a host add to the bundled set, or override part of it, without
/// giving up the rest:
///
/// ```swift
/// TemplateStore.install(LayeredTemplates([TemplateDirectory(url: mine), BundledTemplates()]))
/// ```
public struct LayeredTemplates: TemplateSource {
    public let layers: [any TemplateSource]

    public init(_ layers: [any TemplateSource]) {
        self.layers = layers
    }

    /// Every name any layer supplies, once.
    public func templateNames() -> [String] {
        Array(Set(layers.flatMap { $0.templateNames() })).sorted()
    }

    public func templateData(named name: String) -> Data? {
        for layer in layers {
            if let data = layer.templateData(named: name) { return data }
        }
        return nil
    }
}

/// The page templates the renderer draws under the ink.
///
/// A page refers to a template **by name**, and the store asks its
/// `TemplateSource` for it. Parsed templates are cached: in a hundred-page
/// notebook one and the same template is asked for a hundred times.
///
/// The renderer reads `TemplateStore.shared`, which out of the box draws from
/// `BundledTemplates`: the package's own set, filed under the names the
/// tablet gives its templates, so a page that names one of those gets a
/// background. The host replaces the source with `install(_:)` — its own,
/// its own over the bundled set (`LayeredTemplates`), or `nil` for blank
/// paper. A store can also be made directly, to parse or measure templates
/// without touching what the renderer draws.
public final class TemplateStore: Sendable {
    /// The store the renderer draws from.
    public static var shared: TemplateStore {
        current.withLock { $0 }
    }

    /// Name where templates come from for this process. Once, at its start,
    /// from the composition root; a later call replaces the earlier source
    /// and drops everything cached from it. `nil` is blank paper, and
    /// `BundledTemplates()` goes back to the default.
    public static func install(_ source: (any TemplateSource)?) {
        let store = TemplateStore(source: source)
        current.withLock { $0 = store }
    }

    /// What `shared` draws from until the host installs something else.
    static let defaultSource: any TemplateSource = BundledTemplates()

    private static let current = Mutex(TemplateStore(source: defaultSource))

    private let source: (any TemplateSource)?

    /// The parsed templates and the names known to be missing: searching
    /// again for an absent template is as wasteful as re-reading a found one.
    private let cache = Mutex<[String: Template?]>([:])
    /// A ruling is read off a drawing of the template, which is a page-sized
    /// bitmap: worth doing once per template and page size, and no more.
    let rulings = Mutex<[String: Ruling?]>([:])
    let ruled = Mutex<[String: [RuledTemplate]]>([:])

    public init(source: (any TemplateSource)?) {
        self.source = source
    }

    /// The template with this name, parsed, or `nil` where the source has no
    /// such template or its JSON does not parse.
    public func template(named name: String) -> Template? {
        if let cached = cache.withLock({ $0[name] }) { return cached }

        let loaded = load(name)
        cache.withLock { $0[name] = loaded }
        return loaded
    }

    /// The names the source can supply, sorted.
    public func availableNames() -> [String] {
        source?.templateNames().sorted() ?? []
    }

    private func load(_ name: String) -> Template? {
        guard let source else { return nil }
        guard let data = source.templateData(named: name) else {
            RMRenderLog.pageDebug("template not found: \(name)")
            return nil
        }
        do {
            return try JSONDecoder().decode(Template.self, from: data)
        } catch {
            // An unfamiliar template means a page without a background, not a
            // lost page: the user's drawing matters more than the grid under
            // it.
            RMRenderLog.pageError("template \(name) not parsed: \(String(describing: error))")
            return nil
        }
    }
}
